"""Run the planner N times per case and compare each graph with the hand-written one.

    python experiments/taskgraph/planner_eval/run_eval.py --out <dir> [--repeat 3]
        --case jp-modular=<repo> --case jp-coupled=<repo>
        [--case jr-modular=<repo>] [--case jr-coupled=<repo>]

Each ``<repo>`` is a repository generated by the task's ``make_repo.py`` for
that variant. Every run writes ``<out>/<case>/run<N>/`` (graph, the graph
before the rule-based merge, report, planner logs, comparison) and the script
ends with a summary table, also written to ``<out>/summary.md`` and
``<out>/summary.json``. A failed run is recorded and the next run continues.

``--no-fast-path``, ``--fast-path-lines N`` and ``--no-merge`` are passed on
to ``plan``.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TASKS = HERE.parent
AQOURS_ROOT = HERE.parents[2]
sys.path.insert(0, str(AQOURS_ROOT))

from aqours_code.taskgraph import load_graph  # noqa: E402
from aqours_code.taskgraph.compare import compare_graphs, format_comparison  # noqa: E402
from aqours_code.taskgraph.planner import (  # noqa: E402
    DRAFT_ATTEMPTS,
    MAX_REVISIONS,
    report_path_for,
)
from aqours_code.taskgraph.process import run_process  # noqa: E402

# case name -> (request, hand-written graph), relative to experiments/taskgraph/
CASES: dict[str, tuple[str, str]] = {
    "jp-modular": ("job_platform/request.md", "job_platform/modular/graphs/handwritten.json"),
    "jp-coupled": ("job_platform/request.md", "job_platform/coupled/graphs/handwritten.json"),
    "jr-modular": ("job_runner/request.md", "job_runner/modular/graphs/handwritten.json"),
    "jr-coupled": ("job_runner/request.md", "job_runner/coupled/graphs/handwritten.json"),
}
DEFAULT_FINAL_CHECK = "python -m pytest -q tests"
COLUMNS = ("case", "run", "success", "items", "fast path", "revisions", "before merge",
           "nodes", "critical path", "max width", "test-only", "match", "calls",
           "tokens in / out", "note")


def run_once(case: str, number: int, repo: Path, out_dir: Path, *, final_check: str,
             timeout_s: float, plan_args: tuple[str, ...] = ()) -> dict:
    """Plan once, compare with the hand-written graph, and return one summary row."""
    request, handwritten = (TASKS / part for part in CASES[case])
    run_dir = out_dir / case / f"run{number}"
    run_dir.mkdir(parents=True, exist_ok=True)
    graph_path = run_dir / "graph.json"
    row: dict = {"case": case, "run": number, "success": False, "exit_code": None,
                 "note": ""}
    proc = run_process(
        [sys.executable, "-m", "aqours_code.taskgraph", "plan", str(request),
         "--repo", str(repo), "--out", str(graph_path), "--final-check", final_check,
         "--timeout", str(timeout_s), "--request-id", f"{case}-planner-{number}",
         *plan_args],
        cwd=AQOURS_ROOT,
        timeout=(DRAFT_ATTEMPTS + MAX_REVISIONS + 1) * (timeout_s + 120) + 300)
    (run_dir / "plan_stdout.txt").write_text(proc.output, encoding="utf-8")
    row["exit_code"] = proc.exit_code
    if proc.timed_out:
        row["note"] = "plan timed out"
    report_path = report_path_for(graph_path)
    if report_path.is_file():
        report = json.loads(report_path.read_text(encoding="utf-8"))
        row.update(success=report["success"], revisions=report["revision_rounds"],
                   draft_items=len(report.get("draft_items", [])),
                   fast_path=report.get("fast_path", {}).get("taken"),
                   nodes_before_merge=report.get("nodes_before_merge"),
                   **report["totals"])
    elif not row["note"]:
        row["note"] = f"no report (exit {proc.exit_code}): {proc.output.strip()[-300:]}"
    if graph_path.is_file():
        result = compare_graphs(load_graph(graph_path), load_graph(handwritten), repo)
        (run_dir / "compare.md").write_text(
            format_comparison(result, "planner", "handwritten"), encoding="utf-8")
        (run_dir / "compare.json").write_text(json.dumps(result, indent=2) + "\n",
                                              encoding="utf-8")
        stats = result["planner"]
        row.update(nodes=stats["nodes"], critical_path=stats["critical_path"],
                   max_parallel_width=stats["max_parallel_width"],
                   test_only_nodes=len(stats["test_only_nodes"]),
                   mean_similarity=result["mean_similarity"],
                   validation_errors=stats["errors"])
    return row


def _cell(row: dict, key: str) -> str:
    value = row.get(key)
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def format_summary(rows: list[dict]) -> str:
    """Render the summary rows as a Markdown table."""
    lines = ["| " + " | ".join(COLUMNS) + " |", "|" + " --- |" * len(COLUMNS)]
    for row in rows:
        tokens = (f"{row['input_tokens']} / {row['output_tokens']}"
                  if "input_tokens" in row else "-")
        cells = [row["case"], str(row["run"]), _cell(row, "success"),
                 _cell(row, "draft_items"), _cell(row, "fast_path"),
                 _cell(row, "revisions"), _cell(row, "nodes_before_merge"),
                 _cell(row, "nodes"), _cell(row, "critical_path"),
                 _cell(row, "max_parallel_width"), _cell(row, "test_only_nodes"),
                 _cell(row, "mean_similarity"), _cell(row, "model_calls"), tokens,
                 row.get("note", "").replace("|", "/").replace("\n", " ")]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def parse_case(text: str) -> tuple[str, Path]:
    """Parse ``name=path``."""
    name, sep, path = text.partition("=")
    if not sep or name not in CASES:
        raise argparse.ArgumentTypeError(
            f"expected <case>=<repo> with case one of {', '.join(CASES)}: {text!r}")
    repo = Path(path)
    if not repo.is_dir():
        raise argparse.ArgumentTypeError(f"repository not found: {path}")
    return name, repo


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True, help="directory for all runs")
    parser.add_argument("--repeat", type=int, default=3)
    parser.add_argument("--case", action="append", type=parse_case, required=True,
                        help="<case>=<repo>; case is one of " + ", ".join(CASES))
    parser.add_argument("--final-check", default=DEFAULT_FINAL_CHECK)
    parser.add_argument("--timeout", type=float, default=1800.0,
                        help="timeout in seconds of each planner round")
    parser.add_argument("--no-fast-path", action="store_true",
                        help="always split, whatever the estimate (passed to plan)")
    parser.add_argument("--fast-path-lines", type=int,
                        help="fast-path threshold (passed to plan)")
    parser.add_argument("--no-merge", action="store_true",
                        help="skip the rule-based merge (passed to plan)")
    args = parser.parse_args(argv)
    if args.repeat < 1:
        parser.error("--repeat must be >= 1")
    plan_args: list[str] = []
    if args.no_fast_path:
        plan_args.append("--no-fast-path")
    if args.fast_path_lines is not None:
        plan_args += ["--fast-path-lines", str(args.fast_path_lines)]
    if args.no_merge:
        plan_args.append("--no-merge")
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for case, repo in args.case:
        for number in range(1, args.repeat + 1):
            print(f"[{case} run {number}] planning ...", flush=True)
            try:
                row = run_once(case, number, repo.resolve(), out_dir,
                               final_check=args.final_check, timeout_s=args.timeout,
                               plan_args=tuple(plan_args))
            except Exception as exc:  # noqa: BLE001 - one failed run must not stop the rest
                row = {"case": case, "run": number, "success": False,
                       "note": f"{type(exc).__name__}: {exc}"}
            print(f"[{case} run {number}] success={_cell(row, 'success')} "
                  f"nodes={_cell(row, 'nodes')} match={_cell(row, 'mean_similarity')}",
                  flush=True)
            rows.append(row)
            (out_dir / "summary.json").write_text(json.dumps(rows, indent=2) + "\n",
                                                  encoding="utf-8")
    summary = format_summary(rows)
    (out_dir / "summary.md").write_text(summary, encoding="utf-8")
    print()
    print(summary, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
